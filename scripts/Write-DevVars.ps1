<#
.SYNOPSIS
  Writes the local `.dev.vars` files that the sign-in Workers read when they run on this computer.

.DESCRIPTION
  A Worker cannot open files on the disk, so key files must reach it as settings. Wrangler
  reads a file named `.dev.vars` that sits next to the Worker's configuration file. This script
  builds those files from the key files in `private\dev-private-keys`.

  Files written (each is ignored by Git):
    workers\d1-workers\crud-worker\.dev.vars
        CRUD_WORKER_PRIVATE_KEY   from private-worker-crud-operations-2.pem
    workers\d1-workers\session-worker\.dev.vars
        KR_SESSION_WORKER_SECRET  from session-symmetric-hashkey.key
    apps\api\.dev.vars   (the API's sign-in settings when it runs on this computer)
        KR_APP_BASE_URL               http://localhost:3011 (this computer's address for the web app)
        KR_TURNSTILE_SITE_KEY         Cloudflare's always-pass test site key (public). Matches the test secret below, so
                                      localhost sign-in works without the live widget.
        KR_GOOGLE_CLIENT_SECRET       from google-krhombase-team-client-secret.pem
        KR_TURNSTILE_SECRET_KEY       from turnstile-keys\dev-turnstile-always-valid-key.private
        KR_WORKER_JWT_PRIVATE_KEY     from private-dev-dan-2.pem
        KR_CRUD_WORKER_PUBLIC_KEY     from public-worker-crud-operations-2.pem
        KR_SESSION_WORKER_SECRET      from session-symmetric-hashkey.key
        KR_SUPER_ADMIN_EMAILS         only when -SuperAdminEmails is given

  The script prints setting names and character counts only. It never prints a value.
  It will not replace a `.dev.vars` file that it did not write itself (one without the
  "Generated by" first line) unless -Force is given, so hand-written settings are not lost.

.PARAMETER KeysFolder
  Folder that holds the key files. Default: private\dev-private-keys in the repository root.

.PARAMETER SuperAdminEmails
  Optional, comma-separated. Only needed when the database has no users yet: the listed email may then
  become the first super admin. Leave it out when the database already has users.

.PARAMETER Force
  Replace an existing `.dev.vars` file even when this script did not write it.

.EXAMPLE
  Set-Location D:\Repos\krhomebase
  .\scripts\Write-DevVars.ps1
#>
[CmdletBinding()]
param(
  [string]$KeysFolder = '',
  [string]$SuperAdminEmails = '',
  [switch]$Force
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($KeysFolder)) { $KeysFolder = Join-Path $repoRoot 'private\dev-private-keys' }

$marker = '# Generated by scripts/Write-DevVars.ps1. Do not commit. Safe to delete; run the script again to rebuild.'
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)

# Reads one key file and returns its text with line breaks written as the two characters \n,
# which is how a .dev.vars file holds a value that spans several lines.
# -Kind checks the shape of the file, because the Workers can only use PKCS#8 private keys
# ("BEGIN PRIVATE KEY") and SPKI public keys ("BEGIN PUBLIC KEY"):
#   Private  a PKCS#8 private key     Public  an SPKI public key     Secret  a one-line secret
function Read-KeyValue {
  param([string]$FileName, [ValidateSet('Any', 'Private', 'Public', 'Secret')][string]$Kind = 'Any')
  $path = Join-Path $KeysFolder $FileName
  if (-not (Test-Path -LiteralPath $path)) { throw "Key file not found: $FileName (looked in $KeysFolder)" }
  $text = (Get-Content -LiteralPath $path -Raw).Trim()
  if ($text.Length -eq 0) { throw "Key file is empty: $FileName" }
  if ($Kind -eq 'Private' -and -not $text.StartsWith('-----BEGIN PRIVATE KEY-----')) {
    throw "$FileName must be a PKCS#8 private key (first line '-----BEGIN PRIVATE KEY-----'). If it starts with 'BEGIN RSA PRIVATE KEY', convert a copy: openssl pkcs8 -topk8 -nocrypt -in old.pem -out new.pem"
  }
  if ($Kind -eq 'Public' -and -not $text.StartsWith('-----BEGIN PUBLIC KEY-----')) {
    throw "$FileName must be an SPKI public key (first line '-----BEGIN PUBLIC KEY-----'). If it starts with 'BEGIN RSA PUBLIC KEY', convert a copy: openssl rsa -RSAPublicKey_in -in old.pem -pubout -out new.pem"
  }
  if ($Kind -eq 'Secret' -and ($text.StartsWith('{') -or $text.StartsWith('-----') -or $text -match '\s')) {
    throw "$FileName must hold the secret value only, on one line (not JSON, not a PEM block)."
  }
  if ($text -match '["$`]') { throw "Key file contains a character that cannot be stored safely in .dev.vars: $FileName" }
  return ($text -replace "`r`n", '\n' -replace "`n", '\n')
}

# Writes one .dev.vars file. $Settings is an ordered list of name/value pairs.
function Write-DevVarsFile {
  param([string]$RelativeFolder, [System.Collections.IDictionary]$Settings)
  $folder = Join-Path $repoRoot $RelativeFolder
  if (-not (Test-Path -LiteralPath $folder)) { throw "Worker folder not found: $RelativeFolder" }
  $target = Join-Path $folder '.dev.vars'
  if ((Test-Path -LiteralPath $target) -and -not $Force) {
    $first = Get-Content -LiteralPath $target -TotalCount 1
    if ($first -ne $marker) { throw "$RelativeFolder\.dev.vars exists and was not written by this script. Use -Force to replace it." }
  }
  $lines = @($marker)
  foreach ($name in $Settings.Keys) { $lines += ('{0}="{1}"' -f $name, $Settings[$name]) }
  [System.IO.File]::WriteAllText($target, (($lines -join "`n") + "`n"), $utf8NoBom)
  foreach ($name in $Settings.Keys) {
    '{0}\.dev.vars  {1}  {2} characters' -f $RelativeFolder, $name, $Settings[$name].Length
  }
}

# Collect every value first, so that nothing is written when a key file is missing.
$crudSettings = [ordered]@{
  CRUD_WORKER_PRIVATE_KEY = (Read-KeyValue -FileName 'private-worker-crud-operations-2.pem' -Kind Private)
}
$sessionSettings = [ordered]@{
  KR_SESSION_WORKER_SECRET = (Read-KeyValue -FileName 'session-symmetric-hashkey.key' -Kind Secret)
}
$apiSettings = [ordered]@{
  KR_APP_BASE_URL           = 'http://localhost:3011'
  KR_TURNSTILE_SITE_KEY     = '1x00000000000000000000AA'
  KR_GOOGLE_CLIENT_SECRET   = (Read-KeyValue -FileName 'google-krhombase-team-client-secret.pem' -Kind Secret)
  KR_TURNSTILE_SECRET_KEY   = (Read-KeyValue -FileName 'turnstile-keys\dev-turnstile-always-valid-key.private' -Kind Secret)
  KR_WORKER_JWT_PRIVATE_KEY = (Read-KeyValue -FileName 'private-dev-dan-2.pem' -Kind Private)
  KR_CRUD_WORKER_PUBLIC_KEY = (Read-KeyValue -FileName 'public-worker-crud-operations-2.pem' -Kind Public)
  KR_SESSION_WORKER_SECRET  = $sessionSettings.KR_SESSION_WORKER_SECRET
}
if (-not [string]::IsNullOrWhiteSpace($SuperAdminEmails)) {
  if ($SuperAdminEmails -match '["$`\s]') { throw 'SuperAdminEmails: use plain addresses separated by commas, with no spaces or quotes.' }
  $apiSettings['KR_SUPER_ADMIN_EMAILS'] = $SuperAdminEmails
}

Write-DevVarsFile -RelativeFolder 'workers\d1-workers\crud-worker' -Settings $crudSettings
Write-DevVarsFile -RelativeFolder 'workers\d1-workers\session-worker' -Settings $sessionSettings
Write-DevVarsFile -RelativeFolder 'apps\api' -Settings $apiSettings
'Done. Values were not printed. Counts above include the \n markers that stand for line breaks.'
