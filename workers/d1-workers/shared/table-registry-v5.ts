export type RegisteredTable = keyof typeof TABLE_REGISTRY
export type TableName = RegisteredTable

export function isAllowedTable(table: string): table is RegisteredTable {
  return Object.prototype.hasOwnProperty.call(TABLE_REGISTRY, table)
}

export function getTablePolicy(table: string): TablePolicy {
  if (!isAllowedTable(table)) throw new Error(`Unknown table: ${table}`)
  return TABLE_REGISTRY[table]
}

export function isActionAllowed(table: string, action: CrudAction): boolean {
  if (!isAllowedTable(table)) return false
  const policy = getTablePolicy(table)

  switch (action) {
    case 'CREATE': return policy.allowCreate
    case 'READ': return policy.allowRead
    case 'UPDATE': return policy.allowUpdate
    case 'DELETE': return policy.allowDelete
    case 'SEARCH': return policy.allowRead
    default: return false
  }
}

export function quoteIdentifier(identifier: string): string {
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(identifier)) {
    throw new Error(`Unsafe SQL identifier: ${identifier}`)
  }

  return `"${identifier}"`
}

export function findRejectedColumns(
  table: string,
  action: 'CREATE' | 'UPDATE' | 'SEARCH',
  values: Record<string, unknown>,
): string[] {
  if (!isAllowedTable(table)) return Object.keys(values)
  const policy = getTablePolicy(table)
  const allowed = new Set(
    action === 'CREATE'
      ? policy.createColumns
      : action === 'UPDATE'
        ? policy.updateColumns
        : policy.searchableColumns,
  )

  return Object.keys(values).filter((column) => !allowed.has(column))
}

export function findMissingCreateColumns(
  table: string,
  values: Record<string, unknown>,
): string[] {
  if (!isAllowedTable(table)) return []
  const provided = new Set(Object.keys(values))
  return getTablePolicy(table).requiredCreateColumns.filter((column) => !provided.has(column))
}
