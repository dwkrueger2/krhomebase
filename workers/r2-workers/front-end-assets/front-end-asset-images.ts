export type KRFrontEndAssetImageRecord = {
  /** Stable inventory id derived from the source filename without extension. */
  id: string
  /** Original filename from the available local source folder. */
  filename: string
  /** Human-readable grouping key. Full-size and resized files share a family id. */
  familyId: string
  /** Suggested public-site content category for planning and search. */
  category: KRFrontEndAssetImageCategory
  /** Short display label for admin review. */
  label: string
  /** Source file size from the initial local inventory listing. */
  bytes: number
  /** Image file extension. */
  extension: 'jpg' | 'png' | 'webp'
  /** Width detected from a filename suffix like -400x266 when present. */
  width?: number
  /** Height detected from a filename suffix like -400x266 when present. */
  height?: number
  /** Whether this source file appears to be a source/full asset or an existing resized variant. */
  variant: 'source' | 'thumbnail'
  /** R2 object key. Initial upload convention keeps all image files directly under this prefix. */
  r2Key: string
  /** Public category used by the allow-list and future worker URL routing. */
  publicCategory: KRFrontEndAssetImageCategory
  /** Current migration status for the planned R2 front-end asset migration. */
  status: KRFrontEndAssetImageStatus
}

